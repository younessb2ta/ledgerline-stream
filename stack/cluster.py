def rest(path: str) -> dict:
    with urllib.request.urlopen(f"{REST}{path}", timeout=10) as response:
        return json.loads(response.read())


def rest_ready() -> bool:
    try:
        rest("/overview")
        return True
    except (urllib.error.URLError, TimeoutError, ConnectionError):
        return False


def jobs() -> list[dict]:
    if not rest_ready():
        return []
    return rest("/jobs/overview").get("jobs", [])


def active_job() -> dict | None:
    states = ("RUNNING", "RESTARTING", "INITIALIZING", "CREATED", "FAILING")
    active = [job for job in jobs() if job["state"] in states]
    return active[-1] if active else None


def taskmanagers() -> list[dict]:
    if not rest_ready():
        return []
    return rest("/taskmanagers").get("taskmanagers", [])


def busy_taskmanagers() -> list[dict]:
    """TaskManagers that host at least one slot of work."""
    return [
        manager
        for manager in taskmanagers()
        if manager.get("freeSlots", 0) < manager.get("slotsNumber", 0)
    ]


def taskmanager_pid(manager: dict) -> int | None:
    """Find the OS process behind a TaskManager by its data port."""
    port = manager.get("dataPort")
    if not port:
        return None
    result = subprocess.run(
        ["lsof", "-nP", f"-iTCP:{port}", "-sTCP:LISTEN", "-t"],
        capture_output=True,
        text=True,
    )
    pids = [int(token) for token in result.stdout.split()]
    return pids[0] if pids else None


def kill_taskmanager(manager: dict, *, signal_number: int = 9) -> int:
    pid = taskmanager_pid(manager)
    if pid is None:
        raise SystemExit(f"could not find the process for TaskManager {manager.get('id')}")
    print(f"kill -{signal_number} {pid} ({manager['id']})")
    os.kill(pid, signal_number)
    return pid


def start_taskmanager() -> None:
    tools.run([str(tools.flink_bin("taskmanager.sh")), "start"], env=java_env())


def checkpoints(job_id: str) -> dict:
    return rest(f"/jobs/{job_id}/checkpoints")


def latest_completed_checkpoint(job_id: str) -> dict:
    data = checkpoints(job_id)
    return (data.get("latest", {}) or {}).get("completed") or {}


def wait_for_checkpoint(job_id: str, *, after_id: int = 0, timeout: float = 120.0) -> dict:
    """Wait for a completed checkpoint newer than ``after_id``."""
    holder: dict = {}

    def ready() -> bool:
        try:
            latest = latest_completed_checkpoint(job_id)
        except (urllib.error.URLError, TimeoutError, ConnectionError):
            return False
        holder.update(latest)
        return bool(latest) and int(latest.get("id", 0)) > after_id

    tools.wait_for(f"checkpoint after {after_id}", ready, timeout=timeout)
    return holder


def wait_for_restore(job_id: str, *, timeout: float = 180.0) -> dict:
    """Wait until the job is running again after restoring from a checkpoint."""
    holder: dict = {}

    def restored() -> bool:
        try:
            data = checkpoints(job_id)
            job = next((job for job in jobs() if job["jid"] == job_id), None)
        except (urllib.error.URLError, TimeoutError, ConnectionError):
            return False
        holder.update(data)
        counts = data.get("counts", {})
        return bool(job) and job["state"] == "RUNNING" and counts.get("restored", 0) > 0

    tools.wait_for("job restored from checkpoint", restored, timeout=timeout)
    return holder


def cancel_all() -> None:
    """Cancel every job and wait until no job is in an active state."""
    if not rest_ready():
        return
    active = ("RUNNING", "RESTARTING", "INITIALIZING", "CREATED", "FAILING")
    for job in jobs():
        if job["state"] in active:
            print(f"cancelling {job['jid']} ({job['state']})")
            request = urllib.request.Request(
                f"{REST}/jobs/{job['jid']}?mode=cancel", method="PATCH"
            )
            try:
                urllib.request.urlopen(request, timeout=30).read()
            except urllib.error.URLError as error:
                print(f"cancel request failed: {error}")
    tools.wait_for(
        "all jobs stopped",
        lambda: not any(job["state"] in active for job in jobs()),
        timeout=60,
    )


def up() -> None:
    ensure_installed()
    write_config()
    if rest_ready():
        print("flink already running")
        return
    tools.run([str(tools.flink_bin("start-cluster.sh"))], env=java_env())
    tools.wait_for("flink jobmanager", rest_ready, timeout=90)
    # start-cluster starts one TaskManager; start a second so a kill is survivable
    for index in (2,):
        result = subprocess.run(
            [str(tools.flink_bin("taskmanager.sh")), "start"],
            capture_output=True,
            text=True,
            env=java_env(),
        )
        if result.returncode != 0:
            print(result.stdout, result.stderr)
            raise SystemExit(f"failed to start taskmanager {index}")
    tools.wait_for(
        "two taskmanagers",
        lambda: len(rest("/taskmanagers").get("taskmanagers", [])) >= 2,
        timeout=90,
    )


def down() -> None:
    if not tools.FLINK_HOME.exists():
        print("flink is not installed")
        return
    tools.run([str(tools.flink_bin("stop-cluster.sh"))], check=False, env=java_env())


def status() -> None:
    if not rest_ready():
        print("flink is not running")
        return
    overview = rest("/overview")
    print(
        f"taskmanagers: {overview.get('taskmanagers')}  "
        f"slots: {overview.get('slots-total')} free: {overview.get('slots-available')}"
    )
    active_states = ("RUNNING", "RESTARTING", "INITIALIZING", "CREATED", "FAILING")
    active = [job for job in jobs() if job["state"] in active_states]
    if not active:
        print("jobs: none active")
    for job in active:
        print(f"job {job['jid']} {job['name']} state={job['state']}")
    if active:
        job = active[-1]
        checkpoints = rest(f"/jobs/{job['jid']}/checkpoints")
        latest = (checkpoints.get("latest", {}) or {}).get("completed") or {}
        print(f"latest checkpoint: {latest.get('id')} at {latest.get('trigger_timestamp')}")


def build_jar() -> Path:
    if not JAR.exists() or _jar_is_stale():
        tools.run(
            [
                str(Path.home() / ".local" / "maven" / "bin" / "mvn"),
                "-q",
                "-DskipTests",
                "package",
            ],
            cwd=tools.REPO / "flink-job",
            env=java_env(),
        )
    return JAR


def _jar_is_stale() -> bool:
    if not JAR.exists():
        return True
    jar_mtime = JAR.stat().st_mtime
    sources = list((tools.REPO / "flink-job" / "src").rglob("*.java"))
    sources.append(tools.REPO / "flink-job" / "pom.xml")
    return any(source.stat().st_mtime > jar_mtime for source in sources)


def submit(extra_args: list[str] | None = None) -> str:
    if not rest_ready():
        raise SystemExit("flink is not running; run `python -m stack.cluster up`")
    jar = build_jar()
    command = [
        str(tools.flink_bin("flink")),
        "run",
        "-d",
        "-c",
        MAIN_CLASS,
        str(jar),
        *(
            extra_args
            or [
                "--bootstrap",
                "127.0.0.1:9092",
                "--topic",
                "ledger.events",
                "--group",
                "ledgerline-stream",
                "--jdbc-url",
                tools.PG_JDBC,
                "--jdbc-user",
                tools.PG_USER,
                "--jdbc-password",
                "",
                "--checkpoints",
                f"file://{tools.CHECKPOINTS}",
            ]
        ),
    ]
    result = tools.run(command, capture_output=True, env=java_env())
    print(result.stdout)
    if result.stderr:
        print(result.stderr)
    for token in result.stdout.split():
        if len(token) == 32 and all(character in "0123456789abcdef" for character in token):
            return token
    raise SystemExit("could not parse job id from `flink run`")


def cancel(job_id: str) -> None:
    tools.run([str(tools.flink_bin("flink")), "cancel", job_id], env=java_env())


def main(argv: list[str] | None = None) -> int:
    argv = argv if argv is not None else sys.argv[1:]
    command = argv[0] if argv else "status"
    if command == "up":
        up()
    elif command == "down":
        down()
    elif command == "status":
        status()
    elif command == "submit":
        job_id = submit(argv[1:] or None)
        print(f"submitted {job_id}")
    elif command == "cancel":
        if len(argv) > 1:
            cancel(argv[1])
        else:
            cancel_all()
    elif command == "install":
        ensure_installed()
        write_config()
        print("flink installed at", tools.FLINK_HOME)
    else:
        raise SystemExit(f"unknown command: {command}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
